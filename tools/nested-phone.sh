#!/usr/bin/env bash
# Opal in phone mode inside a nested Hyprland window with the size of a phone.
# The nested shell has its own state folder, its own DBus session and its own Quickshell instance, so the live shell is not changed.
# Usage: tools/nested-phone.sh [width height]   (logical pixels, default 412 915)
set -euo pipefail
width=${1:-412}
height=${2:-915}
[[ $width =~ ^[0-9]+$ && $height =~ ^[0-9]+$ ]] || { echo "Width and height must be whole numbers." >&2; exit 2; }
source_dir=$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../src" && pwd)
state=${OPAL_NESTED_STATE:-${XDG_STATE_HOME:-$HOME/.local/state}/opal/nested-phone}
mkdir -p "$state"
command -v Hyprland >/dev/null && command -v dbus-run-session >/dev/null && command -v quickshell >/dev/null || { echo "Hyprland, dbus-run-session and quickshell are necessary." >&2; exit 1; }
[[ -n ${WAYLAND_DISPLAY:-} ]] || { echo "Run this from a Wayland session." >&2; exit 1; }

# The nested preferences take the look of the live shell, and always start in phone mode on the nested output.
python3 - "$HOME/.local/state/opal/preferences.json" "$state/preferences.json" <<'PY'
import json, pathlib, sys
live, nested = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
try: source = json.loads(live.read_text())
except (OSError, ValueError): source = {}
try: prefs = json.loads(nested.read_text())
except (OSError, ValueError): prefs = {}
for key in ('palette', 'light', 'dynamicColors', 'dynamicPalette', 'colorScheme', 'glass', 'iconStyle', 'wallpaperPath', 'wallpaperFit', 'wallpaper', 'weatherCity', 'weatherFahrenheit', 'favorites', 'phoneButtons', 'phoneRows'):
    if key in source: prefs[key] = source[key]
# No theme files, no Link device and no autostart from the nested shell.
prefs.update(mode='phone', phoneDisplay='WAYLAND-1', linkEnabled=False, themeExport=[], onboarded=True)
nested.write_text(json.dumps(prefs, indent=1))
PY

icon_theme=${QS_ICON_THEME:-$(gsettings get org.gnome.desktop.interface icon-theme 2>/dev/null | tr -d "'" || true)}
kb_layout=$(sed -n 's/^[[:space:]]*kb_layout = "\([^"]*\)".*/\1/p' "${XDG_CONFIG_HOME:-$HOME/.config}/hypr/hyprland.lua" 2>/dev/null | head -1)
cat > "$state/hyprland.lua" <<EOF
-- Generated by tools/nested-phone.sh. The nested output is the phone screen.
hl.monitor({ output = "WAYLAND-1", mode = "${width}x${height}", position = "0x0", scale = 1 })
hl.monitor({ output = "", mode = "preferred", position = "auto", scale = 1 })
hl.config({
    -- A phone shows apps edge to edge: no gaps, no border, no rounding.
    general = { gaps_in = 0, gaps_out = 0, border_size = 0 },
    decoration = { rounding = 0, blur = { enabled = true, size = 6, passes = 2 } },
    input = { kb_layout = "${kb_layout:-us}" },
    cursor = { no_warps = true },
    misc = { disable_hyprland_logo = true, disable_splash_rendering = true },
})
hl.layer_rule({ match = { namespace = "^opal-(bar|shelf|overlay|toast|volume-osd|audio|shade|taskbar-menu|assistant|activity|quick-access)\$" }, blur = true, ignore_alpha = 0.1, no_anim = true })
hl.layer_rule({ match = { namespace = "^opal-(gesture|edge|split|audio-dismiss|shade-dismiss|activity-dismiss|workspaces-dismiss)\$" }, blur = false, no_anim = true })
hl.on("hyprland.start", function()
    hl.exec_cmd("env OPAL_STATE_DIR='$state' OPAL_NESTED=1 QS_ICON_THEME='${icon_theme}' quickshell -n -p '$source_dir/shell.qml'")
end)
EOF

echo "Starting the nested phone (${width}x${height}). Close its window to end it."
# The nested compositor gets a private DBus session: its notification server, players and tray never take over the live ones.
env -u HYPRLAND_INSTANCE_SIGNATURE dbus-run-session -- Hyprland -c "$state/hyprland.lua" > "$state/hyprland.log" 2>&1 &
child=$!

# Float the nested window at phone size, centred on the live screen. All live Hyprland calls go through hypr_actions.
python3 - "$child" "$width" "$height" "$source_dir" "$state" <<'PY'
import os, subprocess, sys, time
child, width, height, source = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3]), sys.argv[4]
sys.path.insert(0, source)
from hypr_actions import HyprActions
hypr = HyprActions()
def descendants(pid):
    out = {pid}
    try:
        for line in subprocess.run(['ps', '-e', '-o', 'pid=,ppid='], capture_output=True, text=True, timeout=3).stdout.splitlines():
            p, pp = map(int, line.split())
            if pp in out: out.add(p)
    except (OSError, ValueError, subprocess.SubprocessError): pass
    return out
deadline = time.time() + 15
while time.time() < deadline:
    pids = descendants(child)
    window = next((c for c in hypr.clients() if c.get('pid') in pids and c.get('mapped')), None)
    if window:
        monitor = next((m for m in hypr.monitors() if m.get('id') == window.get('monitor')), None) or {}
        scale = monitor.get('scale') or 1
        mw, mh = int(monitor.get('width', 1920) / scale), int(monitor.get('height', 1080) / scale)
        x = monitor.get('x', 0) + max(0, (mw - width) // 2)
        y = monitor.get('y', 0) + max(0, (mh - height) // 2)
        hypr.set_floating(window['address'], True)
        hypr.geometry(window['address'], x, y, width, height)
        print('Nested phone window:', window['address'])
        break
    time.sleep(.3)
else:
    print('The nested window did not appear; see', os.path.join(sys.argv[5], 'hyprland.log'), file=sys.stderr)
PY
echo "Log: $state/hyprland.log"
