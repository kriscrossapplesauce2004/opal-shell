#!/usr/bin/env bash
# Opal's floating window mode inside a nested Hyprland, with the staging shell and the staging plugin builds.
# The nested shell has its own state folder, DBus session and Quickshell instance, so the live shell is not changed.
# Usage: tools/nested-float.sh [--headless] [width height]
#   --headless runs it inside a virtual KWin that shows nothing on screen; drive it with tools/vpointer.
set -euo pipefail
headless=0
[[ ${1:-} == --headless ]] && { headless=1; shift; }
width=${1:-1600}
height=${2:-1000}
[[ $width =~ ^[0-9]+$ && $height =~ ^[0-9]+$ ]] || { echo "Width and height must be whole numbers." >&2; exit 2; }
root=$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
source_dir=$root/src
state=${OPAL_NESTED_STATE:-${XDG_STATE_HOME:-$HOME/.local/state}/opal/nested-float}
plugins=$state/plugins
mkdir -p "$state" "$plugins"
command -v Hyprland >/dev/null && command -v dbus-run-session >/dev/null && command -v quickshell >/dev/null || { echo "Hyprland, dbus-run-session and quickshell are necessary." >&2; exit 1; }

# The staging plugins: opal-windowing is built from source; hyprbars is the installed build.
make -s -C "$root/plugins/opal-windowing" >/dev/null
cp "$root/plugins/opal-windowing/opal-windowing.so" "$plugins/"
for bars in "$HOME/.local/share/opal/plugins/hyprbars.so" "$HOME/.local/share/vibeshell/plugins/hyprbars.so"; do
    [[ -f $bars ]] && { cp "$bars" "$plugins/"; break; }
done

python3 - "$HOME/.local/state/opal/preferences.json" "$state/preferences.json" <<'PY'
import json, pathlib, sys
live, nested = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
try: source = json.loads(live.read_text())
except (OSError, ValueError): source = {}
try: prefs = json.loads(nested.read_text())
except (OSError, ValueError): prefs = {}
for key in ('palette', 'light', 'dynamicColors', 'dynamicPalette', 'colorScheme', 'glass', 'iconStyle', 'wallpaperPath', 'wallpaperFit', 'wallpaper', 'favorites'):
    if key in source: prefs[key] = source[key]
# Desktop mode with floating windows; no theme files, no Link device and no autostart from the nested shell.
prefs.update(mode='desktop', floatingMode=True, linkEnabled=False, themeExport=[], onboarded=True)
nested.write_text(json.dumps(prefs, indent=1))
PY

icon_theme=${QS_ICON_THEME:-$(gsettings get org.gnome.desktop.interface icon-theme 2>/dev/null | tr -d "'" || true)}
cat > "$state/hyprland.lua" <<EOF
-- Generated by tools/nested-float.sh.
hl.monitor({ output = "WAYLAND-1", mode = "${width}x${height}", position = "0x0", scale = 1 })
hl.monitor({ output = "", mode = "preferred", position = "auto", scale = 1 })
hl.config({ misc = { disable_hyprland_logo = true, disable_splash_rendering = true }, cursor = { no_warps = true } })
dofile("$source_dir/hyprland.lua")
hl.on("hyprland.start", function()
    hl.exec_cmd("env OPAL_STATE_DIR='$state' OPAL_NESTED=1 QS_ICON_THEME='${icon_theme}' quickshell -n -p '$source_dir/shell.qml'")
end)
EOF

run_nested() {
    env -u HYPRLAND_INSTANCE_SIGNATURE OPAL_STATE_DIR="$state" OPAL_SHELL_PATH="$source_dir/shell.qml" OPAL_PLUGIN_DIR="$plugins/" \
        Hyprland -c "$state/hyprland.lua" > "$state/hyprland.log" 2>&1
}
if (( headless )); then
    # A virtual KWin is the parent compositor: nothing appears on the live screen.
    export -f run_nested; export state source_dir plugins
    setsid dbus-run-session -- bash -c '
        kwin_wayland --virtual --socket opal-float-parent --width '"$((width + 40))"' --height '"$((height + 40))"' --no-lockscreen > "$state/kwin.log" 2>&1 &
        for i in $(seq 100); do [[ -S $XDG_RUNTIME_DIR/opal-float-parent ]] && break; sleep .1; done
        WAYLAND_DISPLAY=opal-float-parent run_nested' > /dev/null 2>&1 &
    echo "Headless nested session starting. Log: $state/hyprland.log"
else
    [[ -n ${WAYLAND_DISPLAY:-} ]] || { echo "Run this from a Wayland session." >&2; exit 1; }
    dbus-run-session -- bash -c "$(declare -f run_nested); state='$state' source_dir='$source_dir' plugins='$plugins' run_nested" &
    echo "Nested floating session starting. Close its window to end it. Log: $state/hyprland.log"
fi
