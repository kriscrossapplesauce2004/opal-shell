class Importer:
    def __init__(self, config_path, assume_opal=False):
        self.config = Path(config_path)
        self.root = self.config.parent
        self.assume_opal = assume_opal
        self.loaded = []
        self.missing = []
        self.vars = {}
        self.env = {}
        self.globals = {}
        self.options = []
        self.monitors = []
        self.window_rules = []
        self.layer_rules = []
        self.workspace_rules = []
        self.curves = []
        self.anims = []
        self.gestures = []
        self.autostart = []
        self.keybinds = []
        self.unmapped = []
        self.ignored = []
        self.errors = []
        self.notes = []
        self.mode_stack = []
        self.when = 'reload'
        self.file = self.config
        self.depth = 0

    # records
    def where(self, line):
        try:
            rel = str(Path(self.file).relative_to(self.root))
        except ValueError:
            rel = str(self.file)
        return f'{rel}:{line}'

    def add_unmapped(self, section, item, reason, src):
        self.unmapped.append({'section': section, 'item': item, 'reason': reason, 'source': src})

    def add_ignored(self, item, reason, src):
        self.ignored.append({'item': item, 'reason': reason, 'source': src})

    def add_error(self, src, message):
        self.errors.append({'source': src, 'message': message})

    # keybinds
    def _ident(self, mods, key, mode):
        return (tuple(sorted(mods)), key.lower(), mode)

    def add_bind(self, mods, key, action, flags, desc, src):
        mode = self.mode_stack[-1] if self.mode_stack else None
        ident = self._ident(mods, key, mode)
        for i, old in enumerate(self.keybinds):
            if self._ident(old['mods'], old['key'], old.get('mode')) == ident:
                self.notes.append(f"{src}: bind {'+'.join(mods + [key])} replaces the bind from {old.get('source')}")
                del self.keybinds[i]
                break
        entry = {'mods': sorted(mods), 'key': key, 'action': action}
        if flags:
            entry['flags'] = flags
        if mode:
            entry['mode'] = mode
        if desc:
            entry['description'] = desc
        entry['source'] = src
        self.keybinds.append(entry)

    def remove_bind(self, mods, key, src):
        mode = self.mode_stack[-1] if self.mode_stack else None
        ident = self._ident(mods, key, mode)
        for i, old in enumerate(self.keybinds):
            if self._ident(old['mods'], old['key'], old.get('mode')) == ident:
                self.notes.append(f"{src}: unbind removes {old.get('source')}")
                del self.keybinds[i]
                return
        self.notes.append(f"{src}: unbind has no earlier bind to remove")

    def bind_action(self, keys_mods, keys_key, disp_name, disp_args, flags, desc, src, label):
        action, reason = map_disp(disp_name, disp_args)
        if action is None:
            if reason == 'ignored':
                self.add_ignored(label, 'no-op dispatcher', src)
            else:
                self.add_unmapped('keybinds', label, reason, src)
            return
        self.add_bind(keys_mods, keys_key, action, flags, desc, src)

    def bind_lua(self, keys, disp, opts, src):
        if not isinstance(keys, str):
            self.add_unmapped('keybinds', repr(keys), 'bind keys are not a string', src)
            return
        try:
            mods, key = parse_lua_keys(keys)
        except ValueError as err:
            self.add_unmapped('keybinds', keys, str(err), src)
            return
        flags, desc = {}, None
        if isinstance(opts, dict):
            for name, value in opts.items():
                if name in ('description', 'desc'):
                    desc = str(value)
                elif name in ('repeating', 'locked', 'release', 'mouse', 'drag'):
                    if truthy(value):
                        flags['repeat' if name == 'repeating' else 'mouse' if name == 'drag' else name] = True
                elif truthy(value):
                    self.add_ignored(f'{keys} option {name}', 'no Luna equivalent', src)
        if key.startswith('mouse:'):
            flags['mouse'] = True
        label = f'{keys} -> {disp.name if isinstance(disp, Disp) else type(disp).__name__}'
        if isinstance(disp, Disp):
            self.bind_action(mods, key, disp.name, disp.args, flags, desc, src, label)
        elif isinstance(disp, LFunc):
            self.add_unmapped('keybinds', label, 'Lua function bound to a key; not mapped', src)
        else:
            self.add_unmapped('keybinds', label, 'dispatcher is not recognised', src)

    # window and layer rules
    def add_window_rule(self, match, effects, name, src):
        mapped_match = {}
        for k, v in match.items():
            key = MATCH_KEYS.get(k)
            if key is None:
                self.add_unmapped('window_rules', f'{name or src} match {k}', 'no Luna match key; rule dropped', src)
                return
            try:
                mapped_match[key] = _b(v) if key in BOOL_MATCH else _s(v)
            except ValueError as err:
                self.add_unmapped('window_rules', f'{name or src} match {k}', str(err), src)
                return
        if not mapped_match:
            self.add_unmapped('window_rules', name or src, 'rule has no match', src)
            return
        eff = {}
        for k, v in effects.items():
            if k in ('name', 'match'):
                continue
            if k == 'enabled':
                if not truthy(v):
                    self.add_unmapped('window_rules', name or src, 'disabled rule; not imported', src)
                    return
                continue
            try:
                if k in BOOL_EFFECTS:
                    eff[BOOL_EFFECTS[k]] = _b(v)
                elif k in ('rounding',):
                    eff['rounding'] = _i(v)
                elif k in ('border_size', 'bordersize'):
                    eff['border_width'] = _i(v)
                elif k in ('size', 'move', 'position'):
                    parsed = self._pair_or_dict(v)
                    if k == 'size':
                        eff['size'] = {'width': parsed[0], 'height': parsed[1]}
                    else:
                        eff['position'] = {'x': parsed[0], 'y': parsed[1]}
                elif k == 'workspace':
                    parts = str(v).split()
                    space = {'id': parts[0].replace('name:', ''), 'focus': 'silent' not in parts[1:]}
                    eff['space'] = space
                elif k == 'opacity':
                    parts = str(v).split()
                    values = [float(p) for p in parts[:2]] if parts else []
                    if not values:
                        raise ValueError('opacity needs a number')
                    eff['opacity'] = {'active': values[0], 'inactive': values[-1]}
                elif k == 'hyprbars:no_bar':
                    self.add_ignored(f'{name or src} {k}', 'Hyprland titlebar plugin; Luna has no plugins', src)
                else:
                    self.add_unmapped('window_rules', f'{name or src} effect {k}', 'no Luna effect', src)
            except (ValueError, IndexError, TypeError) as err:
                self.add_unmapped('window_rules', f'{name or src} effect {k}', str(err), src)
        if not eff:
            self.add_unmapped('window_rules', name or src, 'no supported effect', src)
            return
        rule = {'match': mapped_match, 'effects': eff, 'source': src}
        if name:
            rule['name'] = name
        self.window_rules.append(rule)

    def _pair_or_dict(self, v):
        if isinstance(v, dict):
            return _i(v.get('x')), _i(v.get('y'))
        m = re.fullmatch(r'\s*(-?\d+)[\s,x]+(-?\d+)\s*', str(v))
        if not m:
            raise ValueError(f'not a pair: {v!r}')
        return int(m.group(1)), int(m.group(2))

    def add_layer_rule(self, tbl, src):
        match = tbl.get('match') or {}
        if not isinstance(match, dict) or 'namespace' not in match:
            self.add_unmapped('layer_rules', repr(match), 'layer rule needs a namespace match', src)
            return
        eff = {}
        for k, v in tbl.items():
            if k in ('match', 'name'):
                continue
            try:
                if k in LAYER_BOOL:
                    eff[LAYER_BOOL[k]] = _b(v)
                elif k == 'ignore_alpha':
                    eff['ignore_alpha'] = _f(v)
                else:
                    self.add_unmapped('layer_rules', k, 'no Luna layer effect', src)
            except ValueError as err:
                self.add_unmapped('layer_rules', k, str(err), src)
        if eff:
            self.layer_rules.append({'match': {'namespace': _s(match['namespace'])}, 'effects': eff, 'source': src})

    # monitors, spaces, animations, gestures
    def add_monitor(self, tbl, src):
        out = _s(tbl.get('output', ''))
        entry_match = {}
        if out.startswith('desc:'):
            entry_match['description'] = out[5:]
        elif out == '':
            entry_match['fallback'] = True
        else:
            entry_match['name'] = out
        entry = {'match': entry_match, 'source': src}
        for key in tbl:
            if key not in MONITOR_KEYS and key not in ('output',):
                self.add_unmapped('monitors', f'{out or "fallback"} {key}', 'not in the Luna monitor schema', src)
        try:
            if truthy(tbl.get('disabled')) or truthy(tbl.get('disable')):
                entry['enabled'] = False
            mode = str(tbl.get('mode', 'preferred'))
            if mode in ('preferred', 'highres', 'auto'):
                entry['mode'] = 'preferred'
            else:
                m = re.fullmatch(r'(\d+)x(\d+)(?:@([\d.]+))?', mode)
                if not m:
                    raise ValueError(f'mode {mode!r} not supported')
                obj = {'width': int(m.group(1)), 'height': int(m.group(2))}
                if m.group(3):
                    obj['refresh'] = float(m.group(3))
                entry['mode'] = obj
            pos = str(tbl.get('position', 'auto'))
            if pos == 'auto':
                entry['position'] = 'auto'
            else:
                x, y = self._pair_or_dict(pos)
                entry['position'] = {'x': x, 'y': y}
            if 'scale' in tbl and str(tbl['scale']) != 'auto':
                entry['scale'] = _f(tbl['scale'])
            if 'transform' in tbl:
                t = _i(tbl['transform'])
                if not 0 <= t <= 7:
                    raise ValueError('transform outside 0..7')
                entry['rotation'] = [0, 90, 180, 270][t % 4]
                entry['flipped'] = t >= 4
            if 'vrr' in tbl:
                entry['vrr'] = {0: 'off', 1: 'on', 2: 'fullscreen_only'}[_i(tbl['vrr'])]
            if 'mirror' in tbl:
                entry['mirror'] = _s(tbl['mirror'])
        except (ValueError, KeyError) as err:
            self.add_unmapped('monitors', out or 'fallback', str(err), src)
            return
        self.monitors.append(entry)

    def add_workspace(self, tbl, src):
        wid = _s(tbl.get('workspace', ''))
        parsed = parse_space_id(wid)
        if parsed is None or parsed[0] in ('relative', 'empty'):
            self.add_unmapped('spaces', wid, 'space id not supported', src)
            return
        kind, sid, _ = parsed
        entry = {'id': sid, 'kind': {'id': 'number', 'name': 'named', 'special': 'special'}[kind], 'source': src}
        if 'monitor' in tbl:
            entry['monitor'] = _s(tbl['monitor'])
        for key in ('default', 'persistent'):
            if key in tbl:
                entry[key] = _b(tbl[key])
        for key in tbl:
            if key not in WORKSPACE_KEYS:
                self.add_unmapped('spaces', f'{wid} {key}', 'per-space option not in the Luna schema', src)
        self.workspace_rules.append(entry)

    def add_animation(self, tbl, src):
        rule = {'leaf': _s(tbl.get('leaf', ''))}
        if 'enabled' in tbl:
            rule['enabled'] = _b(tbl['enabled'])
        if 'speed' in tbl:
            rule['speed'] = _f(tbl['speed'])
        curve = tbl.get('bezier', tbl.get('curve'))
        if curve:
            rule['curve'] = _s(curve)
        if tbl.get('style'):
            rule['style'] = _s(tbl['style'])
        rule['source'] = src
        self.anims.append(rule)

    def add_curve(self, name, spec, src):
        points = spec.get('points', spec) if isinstance(spec, dict) else spec
        flat = []
        if isinstance(points, dict):
            points = [points[k] for k in sorted(points, key=lambda x: str(x))]
        for p in points or []:
            if isinstance(p, dict):
                p = [p.get(1), p.get(2)]
            if isinstance(p, list):
                flat.extend(p)
            else:
                flat.append(p)
        try:
            pts = [_f(x) for x in flat]
        except ValueError:
            pts = []
        if len(pts) != 4:
            self.add_unmapped('animations', name, 'curve needs four numbers', src)
            return
        self.curves.append({'name': name, 'points': pts, 'source': src})

    def add_gesture(self, tbl, src):
        action = tbl.get('action')
        if action != 'workspace':
            self.add_unmapped('gestures', repr(action), 'gesture action not supported', src)
            return
        try:
            fingers = _i(tbl.get('fingers'))
            direction = _enum(('horizontal', 'vertical', 'pinch'))(tbl.get('direction'))
        except ValueError as err:
            self.add_unmapped('gestures', repr(tbl), str(err), src)
            return
        self.gestures.append({'fingers': fingers, 'direction': direction, 'action': 'space_swipe', 'source': src})

    # Lua walker
    def load_lua(self, path, src=None):
        try:
            text = Path(path).read_text(encoding='utf-8', errors='replace')
        except OSError as err:
            self.add_error(src or str(path), f'cannot read: {err.strerror}')
            return
        if path not in self.loaded:
            self.loaded.append(path)
        try:
            stmts, perrs = parse_lua(text)
        except LuaError as err:
            self.add_error(self.where_for(path, err.line), str(err))
            return
        for line, msg in perrs:
            self.add_error(self.where_for(path, line), f'syntax: {msg}')
        prev = self.file
        self.file = Path(path)
        try:
            self.exec_block(stmts, Scope())
        finally:
            self.file = prev

    def where_for(self, path, line):
        try:
            rel = str(Path(path).relative_to(self.root))
        except ValueError:
            rel = str(path)
        return f'{rel}:{line}'

    def require(self, name, line):
        if not isinstance(name, str):
            return
        path = self.root / (name.replace('.', '/') + '.lua')
        if path in self.loaded:
            return
        if not path.is_file():
            self.missing.append(str(path))
            self.add_error(self.where(line), f'require: module {name!r} not found')
            return
        self.load_lua(path, self.where(line))

    def dofile(self, name, line):
        if not isinstance(name, str):
            self.add_unmapped('files', 'dofile', 'path is computed at runtime', self.where(line))
            return
        path = Path(os.path.expanduser(name))
        if not path.is_absolute():
            path = self.root / path
        if not path.is_file():
            self.missing.append(str(path))
            self.add_error(self.where(line), f'dofile: {path} not found')
            return
        if self.depth > 20:
            self.add_error(self.where(line), 'dofile nested too deep')
            return
        self.depth += 1
        try:
            self.load_lua(path, self.where(line))
        finally:
            self.depth -= 1

    def exec_block(self, stmts, scope):
        for st in stmts:
            try:
                r = self.exec_stmt(st, scope)
            except RecursionError:
                self.add_error(self.where(st.get('line', 0)), 'recursion limit reached')
                return None
            except Exception as err:  # keep going after a bad statement
                self.add_error(self.where(st.get('line', 0)), f'not executed: {err}')
                continue
            if r is not None and r[0] in ('return', 'break'):
                return r
        return None

    def exec_stmt(self, st, scope):
        k = st['k']
        line = st.get('line', 0)
        if k == 'local':
            vals = self.eval_list(st['exprs'], len(st['names']), scope)
            for name, v in zip(st['names'], vals):
                scope.vars[name] = v
        elif k == 'localfunc':
            scope.vars[st['name']] = LFunc(st['func'][1], st['func'][2], scope, self.file)
        elif k == 'function':
            target = st['target']
            if target[0] == 'name':
                self.set_name(target[1], LFunc(st['func'][1], st['func'][2], scope, self.file), scope)
        elif k == 'assign':
            vals = self.eval_list(st['exprs'], len(st['targets']), scope)
            for target, v in zip(st['targets'], vals):
                if target[0] == 'name':
                    self.set_name(target[1], v, scope)
        elif k == 'callstmt':
            call = st['call']
            if call[3] is not None:
                return None
            fv = self.eval(call[1], scope)
            argv = [self.eval(a, scope) for a in call[2]]
            self.exec_call(fv, argv, line, self.describe(call[1]))
        elif k == 'if':
            for cond, body in st['branches']:
                t = truthy(self.eval(cond, scope))
                if t is None:
                    self.add_unmapped('conditionals', f'lines {line}+', 'condition depends on runtime state; block skipped', self.where(line))
                    return None
                if t:
                    return self.exec_block(body, Scope(scope))
            if st['else'] is not None:
                return self.exec_block(st['else'], Scope(scope))
        elif k == 'do':
            return self.exec_block(st['body'], Scope(scope))
        elif k in ('while', 'repeat'):
            self.add_unmapped('conditionals', f'{k} loop at line {line}', 'loops are not run', self.where(line))
        elif k == 'fornum':
            start = self.eval(st['start'], scope)
            stop = self.eval(st['stop'], scope)
            step = 1 if st['step'] is None else self.eval(st['step'], scope)
            if not all(isinstance(x, int) and not isinstance(x, bool) for x in (start, stop, step)) or step == 0:
                self.add_unmapped('conditionals', f'for loop at line {line}', 'loop bounds are not known', self.where(line))
                return None
            count = 0
            for value in range(start, stop + (1 if step > 0 else -1), step):
                count += 1
                if count > 500:
                    self.add_unmapped('conditionals', f'for loop at line {line}', 'loop longer than 500 steps', self.where(line))
                    break
                inner = Scope(scope)
                inner.vars[st['var']] = value
                r = self.exec_block(st['body'], inner)
                if r is not None and r[0] == 'break':
                    break
                if r is not None and r[0] == 'return':
                    return r
        elif k == 'forin':
            self.add_unmapped('conditionals', f'for-in loop at line {line}', 'loops over runtime data are not run', self.where(line))
        elif k == 'return':
            vals = self.eval_list(st['exprs'], 1, scope) if st['exprs'] else [None]
            return ('return', vals[0])
        elif k == 'break':
            return ('break',)
        return None

    def set_name(self, name, value, scope):
        found = scope.find(name)
        if found is not None:
            found.vars[name] = value
        else:
            self.globals[name] = value

    def eval_list(self, exprs, n, scope):
        vals = [self.eval(e, scope) for e in exprs]
        return vals + [None] * max(0, n - len(vals))

    def describe(self, node):
        if node[0] == 'name':
            return node[1]
        if node[0] == 'index':
            return self.describe(node[1]) + '.' + str(node[2][1])
        return '?'

    def lookup(self, name, scope):
        found = scope.find(name)
        if found is not None:
            return found.vars[name]
        if name in self.globals:
            return self.globals[name]
        if name in BUILTINS:
            return LuaPath((name,))
        return None

    def eval(self, node, scope):
        k = node[0]
        if k == 'lit':
            return node[1]
        if k == 'name':
            return self.lookup(node[1], scope)
        if k == 'paren':
            return self.eval(node[1], scope)
        if k == 'vararg':
            return UNKNOWN
        if k == 'index':
            obj = self.eval(node[1], scope)
            key = self.eval(node[2], scope)
            if isinstance(obj, LuaPath):
                return LuaPath(obj.parts + (str(key),))
            if isinstance(obj, dict):
                return obj.get(key)
            return UNKNOWN
        if k == 'table':
            out, n = {}, 0
            for key_node, value_node in node[1]:
                value = self.eval(value_node, scope)
                if key_node is None:
                    n += 1
                    out[n] = value
                else:
                    out[self.eval(key_node, scope)] = value
            return out
        if k == 'func':
            return LFunc(node[1], node[2], scope, self.file)
        if k == 'un':
            v = self.eval(node[2], scope)
            if v is UNKNOWN:
                return UNKNOWN
            if node[1] == 'not':
                return not truthy(v)
            if node[1] == '-' and isinstance(v, (int, float)) and not isinstance(v, bool):
                return -v
            return UNKNOWN
        if k == 'bin':
            return self.eval_bin(node[1], node[2], node[3], scope)
        if k == 'call':
            return self.eval_call(node, scope)
        return UNKNOWN

    def eval_bin(self, op, left, right, scope):
        if op in ('or', 'and'):
            lv = self.eval(left, scope)
            t = truthy(lv)
            if t is None:
                return UNKNOWN
            if op == 'or':
                return lv if t else self.eval(right, scope)
            return self.eval(right, scope) if t else lv
        lv = self.eval(left, scope)
        rv = self.eval(right, scope)
        if lv is UNKNOWN or rv is UNKNOWN:
            return UNKNOWN
        if op == '..':
            if isinstance(lv, (str, int, float)) and isinstance(rv, (str, int, float)) and not isinstance(lv, bool) and not isinstance(rv, bool):
                return _lua_str(lv) + _lua_str(rv)
            return UNKNOWN
        if op in ('==', '~='):
            same = lv == rv
            return same if op == '==' else not same
        if op in ('+', '-', '*') and all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in (lv, rv)):
            return lv + rv if op == '+' else lv - rv if op == '-' else lv * rv
        return UNKNOWN

    def eval_call(self, node, scope):
        fn_node, args, method = node[1], node[2], node[3]
        if method is not None:
            return UNKNOWN
        fv = self.eval(fn_node, scope)
        argv = [self.eval(a, scope) for a in args]
        if isinstance(fv, LuaPath):
            p = fv.parts
            if p[:2] == ('hl', 'dsp') and len(p) > 2:
                return Disp('.'.join(p[2:]), argv)
            if p == ('os', 'getenv'):
                key = argv[0] if argv else None
                if key is UNKNOWN:
                    return UNKNOWN
                return os.environ.get(key) if isinstance(key, str) else None
            if p == ('tostring',):
                v = argv[0] if argv else None
                if v is UNKNOWN:
                    return UNKNOWN
                return _lua_str(v)
            if p == ('io', 'open'):
                path = argv[0] if argv else None
                if self.assume_opal and isinstance(path, str) and path.endswith('opal-active'):
                    return Handle()
                return UNKNOWN
            return UNKNOWN
        if isinstance(fv, LFunc):
            return self.call_function(fv, argv)
        return UNKNOWN

    def exec_call(self, fv, argv, line, text):
        src = self.where(line)
        if isinstance(fv, LuaPath):
            p = fv.parts
            if p == ('pcall',):
                if argv:
                    self.exec_call(argv[0], argv[1:], line, text)
                return
            if p == ('dofile',):
                self.dofile(argv[0] if argv else None, line)
                return
            if p == ('require',):
                self.require(argv[0] if argv else None, line)
                return
            if p and p[0] == 'hl':
                self.hl_call(p[1:], argv, line)
                return
            self.add_ignored(f'runtime call {".".join(p)}', 'runtime code; no config effect', src)
            return
        if isinstance(fv, LFunc):
            self.call_function(fv, argv)
            return
        if fv is UNKNOWN:
            self.add_ignored(f'call of {text}', 'runtime value; no config effect', src)
            return
        self.add_error(src, f'attempt to call {text}')

    def call_function(self, fn, argv):
        if self.depth > 40:
            self.add_error(self.where(fn.body[0].get('line', 0) if fn.body else 0), 'call depth limit reached')
            return None
        scope = Scope(fn.scope)
        for i, name in enumerate(fn.params):
            if name != '...':
                scope.vars[name] = argv[i] if i < len(argv) else None
        prev = self.file
        self.file = fn.file
        self.depth += 1
        try:
            r = self.exec_block(fn.body, scope)
        finally:
            self.depth -= 1
            self.file = prev
        if r is not None and r[0] == 'return':
            return r[1]
        return None

    def run_login_handler(self, fn):
        prev = self.when
        self.when = 'login'
        try:
            self.call_function(fn, [])
        finally:
            self.when = prev

    def hl_call(self, sub, argv, line):
        name = '.'.join(sub)
        src = self.where(line)
        a0 = argv[0] if argv else None
        if name == 'config':
            if isinstance(a0, dict):
                self.flatten_config(a0, [], src)
            else:
                self.add_unmapped('options', 'hl.config', 'argument is not a table', src)
        elif name == 'env':
            if len(argv) >= 2:
                self.env[_s(a0)] = _s(argv[1])
        elif name == 'monitor' and isinstance(a0, dict):
            self.add_monitor(a0, src)
        elif name == 'workspace_rule' and isinstance(a0, dict):
            self.add_workspace(a0, src)
        elif name == 'window_rule' and isinstance(a0, dict):
            self.add_window_rule(a0.get('match') or {}, a0, _s(a0['name']) if 'name' in a0 else None, src)
        elif name == 'layer_rule' and isinstance(a0, dict):
            self.add_layer_rule(a0, src)
        elif name == 'animation' and isinstance(a0, dict):
            self.add_animation(a0, src)
        elif name == 'curve' and isinstance(a0, str):
            self.add_curve(a0, argv[1] if len(argv) > 1 else None, src)
        elif name == 'gesture' and isinstance(a0, dict):
            self.add_gesture(a0, src)
        elif name == 'bind':
            self.bind_lua(a0, argv[1] if len(argv) > 1 else None, argv[2] if len(argv) > 2 else None, src)
        elif name == 'unbind' and isinstance(a0, str):
            try:
                mods, key = parse_lua_keys(a0)
                self.remove_bind(mods, key, src)
            except ValueError as err:
                self.add_unmapped('keybinds', a0, str(err), src)
        elif name == 'on':
            fn = argv[1] if len(argv) > 1 else None
            if a0 == 'hyprland.start' and isinstance(fn, LFunc):
                self.run_login_handler(fn)
            else:
                self.add_unmapped('events', str(a0), 'event handler is not mapped', src)
        elif name == 'define_submap':
            fn = argv[-1] if argv else None
            if isinstance(a0, str) and isinstance(fn, LFunc):
                self.mode_stack.append(a0)
                try:
                    self.call_function(fn, [])
                finally:
                    self.mode_stack.pop()
            else:
                self.add_unmapped('keybinds', 'define_submap', 'submap body is not a function', src)
        elif name == 'exec_cmd':
            if isinstance(a0, str):
                self.autostart.append({'command': a0, 'when': self.when, 'source': src})
        elif name.startswith('plugin'):
            self.add_ignored(f'hl.{name}', 'Hyprland plugin call; Luna has no plugins', src)
        else:
            self.add_unmapped('hyprland_api', f'hl.{name}', 'not mapped', src)

    def flatten_config(self, tbl, prefix, src):
        for key, value in tbl.items():
            path = prefix + [str(key)]
            if isinstance(value, dict):
                self.flatten_config(value, path, src)
            else:
                self.options.append(('.'.join(path), value, src))

    # conf reader
    def read_conf(self, path, src=None):
        try:
            lines = Path(path).read_text(encoding='utf-8', errors='replace').splitlines()
        except OSError as err:
            self.add_error(src or str(path), f'cannot read: {err.strerror}')
            return
        if path not in self.loaded:
            self.loaded.append(path)
        prev = self.file
        self.file = Path(path)
        sections = []
        try:
            for lineno, raw in enumerate(lines, 1):
                line = raw.strip()
                where = self.where_for(path, lineno)
                if not line or line.startswith('#'):
                    continue
                m = re.fullmatch(r'\$([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)', line)
                if m:
                    self.vars[m.group(1)] = self.subst(m.group(2).strip())
                    continue
                m = re.fullmatch(r'([A-Za-z0-9_.:\-]+)\s*\{', line)
                if m:
                    sections.append(m.group(1))
                    continue
                if line == '}':
                    if sections:
                        sections.pop()
                    else:
                        self.add_error(where, 'unmatched }')
                    continue
                m = re.fullmatch(r'([A-Za-z0-9_.:\-\[\]]+)\s*=\s*(.*)', line)
                if not m:
                    self.add_error(where, 'malformed line')
                    continue
                self.conf_key(m.group(1), self.subst(m.group(2).strip()), sections, where, path)
        finally:
            self.file = prev

    def subst(self, text):
        return re.sub(r'\$([A-Za-z_][A-Za-z0-9_]*)', lambda m: self.vars.get(m.group(1), m.group(0)), text)

    def conf_key(self, key, val, sections, where, path):
        parts = [p.strip() for p in val.split(',')]
        if key == 'source':
            target = Path(os.path.expanduser(val))
            if not target.is_absolute():
                target = Path(path).parent / target
            if target.is_file():
                self.read_conf(target, where)
            else:
                self.missing.append(str(target))
                self.add_error(where, f'source: {target} not found')
        elif key.startswith('bind'):
            self.conf_bind(key, val, where)
        elif key == 'unbind':
            try:
                mods = self.conf_mods(parts[0])
                self.remove_bind(mods, norm_key(parts[1]), where)
            except (IndexError, ValueError) as err:
                self.add_unmapped('keybinds', val, str(err), where)
        elif key in ('windowrule', 'windowrulev2'):
            self.conf_window_rule(key, val, where)
        elif key == 'layerrule':
            eff, _, ns = val.partition(',')
            self.add_layer_rule({'match': {'namespace': ns.strip()}, eff.strip(): True}, where)
        elif key == 'monitor':
            self.conf_monitor(parts, where)
        elif key == 'workspace':
            tbl = {'workspace': parts[0]}
            for p in parts[1:]:
                k, _, v = p.partition(':')
                if k == 'monitor':
                    tbl['monitor'] = v
                elif k in ('default', 'persistent'):
                    tbl[k] = v
                else:
                    self.add_unmapped('spaces', p, 'per-space option not in the Luna schema', where)
            self.add_workspace(tbl, where)
        elif key in ('exec-once', 'exec'):
            self.autostart.append({'command': val, 'when': 'login' if key == 'exec-once' else 'reload', 'source': where})
        elif key == 'env':
            name, _, value = val.partition(',')
            self.env[name.strip()] = value.strip()
        elif key == 'bezier':
            self.add_curve(parts[0], [float(p) for p in parts[1:5]] if len(parts) >= 5 and all(re.fullmatch(r'-?\d*\.?\d+', p) for p in parts[1:5]) else None, where)
        elif key == 'animation':
            tbl = {'leaf': parts[0]}
            if len(parts) > 1:
                tbl['enabled'] = parts[1]
            if len(parts) > 2:
                tbl['speed'] = parts[2]
            if len(parts) > 3 and parts[3]:
                tbl['bezier'] = parts[3]
            if len(parts) > 4 and parts[4]:
                tbl['style'] = parts[4]
            self.add_animation(tbl, where)
        elif key == 'gesture':
            if len(parts) >= 3:
                self.add_gesture({'fingers': parts[0], 'direction': parts[1], 'action': parts[2]}, where)
            else:
                self.add_unmapped('gestures', val, 'gesture needs three fields', where)
        elif key == 'submap':
            self.mode_stack = [] if val == 'reset' else [val]
        elif key.startswith('plugin'):
            self.add_ignored(key, 'Hyprland plugin line; Luna has no plugins', where)
        else:
            option = '.'.join(sections + [key])
            self.options.append((option, typed(val), where))

    def conf_mods(self, text):
        names = []
        for tok in re.split(r'[\s+]+', text.strip()):
            if not tok:
                continue
            name = MOD_NAMES.get(tok.upper())
            if name is None:
                raise ValueError(f'unknown modifier {tok!r}')
            if name not in names:
                names.append(name)
        return sorted(names)

    def conf_bind(self, key, val, where):
        flags_letters = key[4:]
        desc = None
        if 'd' in flags_letters:
            parts = [p.strip() for p in val.split(',', 4)]
            if len(parts) < 4:
                self.add_unmapped('keybinds', val, 'bindd needs a description and dispatcher', where)
                return
            desc = parts[2]
            mods_text, key_text, disp = parts[0], parts[1], parts[3]
            arg = parts[4] if len(parts) > 4 else ''
        else:
            parts = [p.strip() for p in val.split(',', 3)]
            if len(parts) < 3:
                self.add_unmapped('keybinds', val, 'bind needs a dispatcher', where)
                return
            mods_text, key_text, disp = parts[0], parts[1], parts[2]
            arg = parts[3] if len(parts) > 3 else ''
        try:
            mods = self.conf_mods(mods_text)
        except ValueError as err:
            self.add_unmapped('keybinds', val, str(err), where)
            return
        flags = {}
        if 'm' in flags_letters or key_text.startswith('mouse:'):
            flags['mouse'] = True
        if 'e' in flags_letters:
            flags['repeat'] = True
        if 'l' in flags_letters:
            flags['locked'] = True
        if 'r' in flags_letters:
            flags['release'] = True
        key_norm = norm_key(key_text)
        label = f'{mods_text}, {key_text}, {disp}'
        legacy = legacy_dispatch(disp, arg, flags.get('mouse', False))
        if legacy is None:
            self.add_unmapped('keybinds', label, f"dispatcher '{disp}' has no Luna action", where)
            return
        self.bind_action(mods, key_norm, legacy[0], legacy[1], flags, desc, where, label)

    def conf_window_rule(self, key, val, where):
        parts = [p.strip() for p in val.split(',')]
        match = {}
        if key == 'windowrule':
            effect = parts[0]
            rest = ','.join(parts[1:]).strip()
            if re.match(r'(class|title|initialclass|initialtitle|floating|fullscreen|pinned|xwayland|focus|tag|workspace):', rest):
                matchers = [rest]
            else:
                matchers = [f'class:{rest}']
        else:
            effect = parts[0]
            matchers = parts[1:]
        for m in matchers:
            name, sep, rx = m.partition(':')
            if not sep:
                self.add_unmapped('window_rules', m, 'matcher without a value', where)
                return
            if name not in ('class', 'title', 'initialclass', 'initialtitle', 'floating', 'fullscreen', 'pinned', 'xwayland', 'focus'):
                self.add_unmapped('window_rules', m, f'matcher {name} has no Luna equivalent; rule dropped', where)
                return
            match[name] = rx
        eff_name, _, eff_arg = effect.partition(' ')
        eff_name = eff_name.strip()
        eff_arg = eff_arg.strip()
        if eff_name in BOOL_EFFECTS or eff_name in ('noanim', 'nofocus', 'noinitialfocus'):
            effects = {eff_name: True}
        elif eff_name in ('size', 'move', 'opacity', 'workspace', 'rounding', 'bordersize'):
            effects = {('border_size' if eff_name == 'bordersize' else eff_name): eff_arg}
        else:
            self.add_unmapped('window_rules', effect, 'no Luna effect', where)
            return
        self.add_window_rule(match, effects, None, where)

    def conf_monitor(self, parts, where):
        name = parts[0]
        if len(parts) > 1 and parts[1] == 'disable':
            self.add_monitor({'output': name, 'disabled': True}, where)
            return
        tbl = {'output': name}
        if len(parts) > 1 and parts[1]:
            tbl['mode'] = parts[1]
        if len(parts) > 2 and parts[2]:
            tbl['position'] = parts[2]
        if len(parts) > 3 and parts[3]:
            tbl['scale'] = parts[3]
        extras = parts[4:]
        for i in range(0, len(extras) - 1, 2):
            tbl[extras[i]] = extras[i + 1]
        self.add_monitor(tbl, where)

    def build(self):
        """Assemble the config and the report."""
        redacted = 0
        opts_applied = []
        policy = {'cursor_warps': False, 'unexpected_float': 'tile', 'mode_exit': 'restore_windows'}
        out = {}
        for path, value, src in self.options:
            if path == 'autogenerated' or path.startswith(IGNORED_PREFIXES):
                self.add_ignored(path, 'Hyprland internal or plugin setting', src)
                continue
            spec = OPTION_MAP.get(path)
            if spec is None:
                self.add_unmapped('options', f'{path} = {value!r}', 'no Luna equivalent yet', src)
                continue
            target, conv = spec
            try:
                converted = conv(value)
            except ValueError as err:
                self.add_unmapped('options', path, str(err), src)
                continue
            if target[0] == 'policy':
                policy[target[1]] = converted
            else:
                set_path(out, target, converted)
            opts_applied.append(path)
        env_out = {}
        for name, value in self.env.items():
            text, n = redact(value)
            redacted += n
            env_out[name] = text
        cursor = out.setdefault('cursor', {})
        if 'XCURSOR_THEME' in env_out:
            cursor.setdefault('theme', env_out['XCURSOR_THEME'])
        if 'XCURSOR_SIZE' in env_out and env_out['XCURSOR_SIZE'].isdigit():
            cursor.setdefault('size', int(env_out['XCURSOR_SIZE']))
        autostart = []
        for item in self.autostart:
            text, n = redact(item['command'])
            redacted += n
            autostart.append({'command': text, 'when': item['when'], 'source': item['source']})
        keybinds = []
        for kb in self.keybinds:
            entry = dict(kb)
            if entry['action'].get('type') == 'exec':
                entry['action'] = dict(entry['action'])
                entry['action']['command'], n = redact(entry['action']['command'])
                redacted += n
            if 'description' in entry:
                entry['description'], n = redact(entry['description'])
                redacted += n
            keybinds.append(entry)
        files = [str(p) for p in self.loaded]
        cfg = {
            'version': 1,
            'source': {'compositor': 'hyprland', 'files': [self._tilde(f) for f in files]},
            'policy': policy,
            'keybinds': keybinds,
            'window_rules': self.window_rules,
            'layer_rules': self.layer_rules,
            'spaces': self.workspace_rules,
            'monitors': self.monitors,
            'input': out.get('input', {}),
            'cursor': cursor,
            'layout': out.get('layout', {}),
            'animations': self._animations(out),
            'gestures': self.gestures,
            'environment': env_out,
            'autostart': autostart,
        }
        for key in ('window_rules', 'layer_rules', 'spaces', 'monitors', 'gestures'):
            for item in cfg[key]:
                if item.get('name') is None:
                    item.pop('name', None)
        for rule in cfg['window_rules'] + cfg['layer_rules'] + cfg['spaces'] + cfg['monitors'] + cfg['gestures'] + cfg['autostart']:
            if 'source' in rule and rule['source'] is None:
                rule.pop('source')
        self.notes.append('Policy values (cursor_warps, unexpected_float, mode_exit) follow section 7.1; the file sets only cursor.no_warps.')
        if not self.keybinds and not self.options:
            self.notes.append('No keybinds or options were read; check the config path.')
        report = {
            'files': {'loaded': [self._tilde(f) for f in files],
                      'not_loaded': self._not_loaded(files),
                      'missing': [self._tilde(m) for m in self.missing]},
            'counts': {
                'keybinds': len(keybinds), 'window_rules': len(self.window_rules),
                'layer_rules': len(self.layer_rules), 'spaces': len(self.workspace_rules),
                'monitors': len(self.monitors), 'gestures': len(self.gestures),
                'autostart': len(autostart), 'options_mapped': len(opts_applied),
                'environment': len(env_out), 'unmapped': len(self.unmapped),
                'ignored': len(self.ignored), 'errors': len(self.errors),
            },
            'unmapped': self.unmapped,
            'ignored': self.ignored,
            'errors': self.errors,
            'notes': self.notes,
            'redacted': redacted,
        }
        return cfg, report

    def _animations(self, out):
        anim = dict(out.get('animations', {}))
        anim['engine'] = 'springs'
        if self.curves or self.anims:
            anim['recorded'] = {'curves': self.curves, 'rules': self.anims}
            anim['note'] = 'Hyprland curves and speeds are recorded for reference. Luna uses springs.'
        return anim

    def _tilde(self, path):
        home = str(Path.home())
        return '~' + path[len(home):] if path.startswith(home) else path

    def _not_loaded(self, loaded):
        seen = {str(p) for p in loaded}
        found = []
        for base in [self.root] + [self.root / d for d in ('dms', 'modules', 'hyprland')]:
            if not base.is_dir():
                continue
            for pattern in ('*.lua', '*.conf'):
                for p in sorted(base.glob(pattern)):
                    if str(p) in seen or '.bak' in p.name or '.pre-' in p.name or 'example' in p.name:
                        continue
                    found.append(self._tilde(str(p)))
        return found


def typed(v):
    if v.lower() in ('true', 'false'):
        return v.lower() == 'true'
    if re.fullmatch(r'-?\d+', v):
        return int(v)
    if re.fullmatch(r'-?\d*\.\d+', v):
        return float(v)
    return v


def import_config(path, assume_opal=False):
    """Read a Lua or legacy .conf config. Return (config, report)."""
    imp = Importer(path, assume_opal=assume_opal)
    p = Path(path)
    if not p.is_file():
        raise FileNotFoundError(str(p))
    if p.suffix == '.conf':
        imp.read_conf(p)
    else:
        imp.load_lua(p)
    return imp.build()


