# ---------- option and value conversion ----------

def _b(v):
    if isinstance(v, bool):
        return v
    if isinstance(v, (int, float)):
        return v != 0
    s = str(v).strip().lower()
    if s in ('1', 'true', 'yes', 'on'):
        return True
    if s in ('0', 'false', 'no', 'off'):
        return False
    raise ValueError(f'not a boolean: {v!r}')


def _i(v):
    if isinstance(v, bool):
        raise ValueError('not an integer')
    if isinstance(v, int):
        return v
    if isinstance(v, float) and v.is_integer():
        return int(v)
    if isinstance(v, str) and re.fullmatch(r'-?\d+', v.strip()):
        return int(v.strip())
    raise ValueError(f'not an integer: {v!r}')


def _f(v):
    if isinstance(v, bool):
        raise ValueError('not a number')
    if isinstance(v, (int, float)):
        return float(v)
    if isinstance(v, str) and re.fullmatch(r'-?\d*\.?\d+', v.strip()):
        return float(v.strip())
    raise ValueError(f'not a number: {v!r}')


def _s(v):
    if isinstance(v, str):
        return v
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return _lua_str(v)
    raise ValueError(f'not a string: {v!r}')


def _color(v):
    s = str(v).strip()
    m = re.fullmatch(r'rgba?\(([0-9a-fA-F]{6}|[0-9a-fA-F]{8})\)', s)
    if m:
        return '#' + m.group(1).upper()
    m = re.fullmatch(r'0x([0-9a-fA-F]{8})', s)
    if m:
        g = m.group(1)
        return ('#' + g[2:] + g[:2]).upper()
    raise ValueError(f'unsupported colour: {v!r}')


def _pair(v):
    m = re.fullmatch(r'\s*(-?\d+)[\s,]+(-?\d+)\s*', str(v))
    if not m:
        raise ValueError(f'not a pair: {v!r}')
    return [int(m.group(1)), int(m.group(2))]


def _enum(allowed):
    def conv(v):
        s = _s(v)
        if s not in allowed:
            raise ValueError(f'unsupported value: {s!r}')
        return s
    return conv


def _follow(v):
    return _i(v) != 0


def _nowarps(v):
    return not _b(v)


def _sens(v):
    x = _f(v)
    if not -1 <= x <= 1:
        raise ValueError('sensitivity outside -1..1')
    return x


