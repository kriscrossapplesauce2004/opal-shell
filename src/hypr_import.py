def set_path(d, path, value):
    for key in path[:-1]:
        d = d.setdefault(key, {})
    d[path[-1]] = value


def parse_lua_keys(text):
    """Split 'SUPER + SHIFT + Q' into (mods, key). Raise ValueError on bad input."""
    parts = [p.strip() for p in text.split('+')]
    if len(parts) < 1 or not parts[-1]:
        raise ValueError('no key')
    mods = []
    for p in parts[:-1]:
        name = MOD_NAMES.get(p.upper())
        if name is None:
            raise ValueError(f'unknown modifier {p!r}')
        if name not in mods:
            mods.append(name)
    return sorted(mods), norm_key(parts[-1])


def norm_key(k):
    return k.upper() if len(k) == 1 and k.isalpha() else k


def parse_space_id(value):
    """Return (kind, id, relative) for a workspace value, or None."""
    s = str(value).strip()
    m = re.fullmatch(r'e([+-]\d+)', s)
    if m:
        return ('relative', int(m.group(1)), None)
    if s.startswith('name:'):
        return ('name', s[5:], None)
    if s.startswith('special'):
        return ('special', s.split(':', 1)[1] if ':' in s else 'special', None)
    if s == 'empty':
        return ('empty', None, None)
    if re.fullmatch(r'-?\d+', s):
        return ('id', s, None)
    return None


def space_target(value):
    parsed = parse_space_id(value)
    if parsed is None:
        return None
    kind, val, _ = parsed
    target = {'kind': kind}
    if val is not None:
        target['value'] = val
    return target


def map_disp(name, args):
    """Map a dispatcher to a Luna action. Return (action, reason)."""
    a0 = args[0] if args else None
    tbl = a0 if isinstance(a0, dict) else {}
    if name == 'exec_cmd':
        return ({'type': 'exec', 'command': a0}, None) if isinstance(a0, str) and a0 else (None, 'exec without command')
    if name == 'window.close':
        return {'type': 'close_window'}, None
    if name == 'window.kill':
        return {'type': 'close_window', 'force': True}, None
    if name == 'focus':
        if 'direction' in tbl and tbl['direction'] in DIRS:
            return {'type': 'focus', 'direction': DIRS[tbl['direction']]}, None
        if 'monitor' in tbl and tbl['monitor'] in DIRS:
            return {'type': 'focus_monitor', 'direction': DIRS[tbl['monitor']]}, None
        if 'window' in tbl and tbl['window'] in ('first', 'last'):
            return {'type': 'focus_window_edge', 'edge': tbl['window']}, None
        if 'workspace' in tbl:
            target = space_target(tbl['workspace'])
            if target:
                return {'type': 'space', 'target': target}, None
        return None, f'focus target {tbl!r} not supported'
    if name == 'window.move':
        if 'direction' in tbl and tbl['direction'] in DIRS:
            return {'type': 'move_focused', 'direction': DIRS[tbl['direction']]}, None
        if 'monitor' in tbl and tbl['monitor'] in DIRS:
            return {'type': 'move_to_monitor', 'direction': DIRS[tbl['monitor']]}, None
        if 'workspace' in tbl:
            target = space_target(tbl['workspace'])
            if target:
                action = {'type': 'space', 'target': target, 'move_window': True}
                if 'follow' in tbl:
                    action['follow'] = bool(tbl['follow'])
                return action, None
        return None, f'move target {tbl!r} not supported'
    if name == 'window.resize':
        if not tbl:
            return {'type': 'resize_mouse'}, None
        try:
            if tbl.get('exact') and 'x' in tbl and 'y' in tbl:
                return {'type': 'resize', 'relative': False, 'width': _i(tbl['x']), 'height': _i(tbl['y'])}, None
            if tbl.get('relative') and ('x' in tbl or 'y' in tbl):
                return {'type': 'resize', 'relative': True, 'dx': _i(tbl.get('x', 0)), 'dy': _i(tbl.get('y', 0))}, None
        except ValueError as err:
            return None, f'resize values: {err}'
        return None, 'resize without relative or exact is not mapped'
    if name == 'window.drag':
        return {'type': 'move_mouse'}, None
    if name == 'window.float':
        mode = tbl.get('action', 'toggle')
        if mode in ('toggle', 'enable', 'disable'):
            return {'type': 'float', 'mode': mode}, None
        return None, f'float action {mode!r} not supported'
    if name == 'window.fullscreen':
        mode = {'maximized': 'maximize', 'fullscreen': 'fullscreen'}.get(tbl.get('mode'))
        if mode is None:
            return None, 'fullscreen mode not supported'
        action = tbl.get('action', 'toggle')
        return {'type': 'fullscreen', 'mode': mode, 'action': action}, None
    if name == 'window.pin':
        return {'type': 'pin'}, None
    if name == 'window.center':
        return {'type': 'center'}, None
    if name in ('window.alter_zorder', 'window.bring_to_top'):
        return {'type': 'raise'}, None
    if name == 'window.pseudo':
        return {'type': 'layout', 'op': 'pseudo'}, None
    if name == 'group.toggle':
        return {'type': 'group', 'op': 'toggle'}, None
    if name == 'group.next':
        return {'type': 'group', 'op': 'next'}, None
    if name == 'group.prev':
        return {'type': 'group', 'op': 'prev'}, None
    if name == 'group.lock':
        return {'type': 'group', 'op': 'lock'}, None
    if name == 'layout':
        msg = str(a0 or '').split()
        if msg[:1] == ['togglesplit']:
            return {'type': 'layout', 'op': 'toggle_split'}, None
        if msg[:1] == ['pseudo']:
            return {'type': 'layout', 'op': 'pseudo'}, None
        if msg[:1] == ['preselect'] and len(msg) == 2 and msg[1] in DIRS:
            return {'type': 'layout', 'op': 'preselect', 'direction': DIRS[msg[1]]}, None
        return None, f'layout message {a0!r} not supported'
    if name == 'submap':
        if a0 == 'reset':
            return {'type': 'mode', 'op': 'leave'}, None
        return {'type': 'mode', 'op': 'enter', 'name': str(a0)}, None
    if name == 'dpms':
        action = tbl.get('action', a0) if tbl else a0
        if action in ('toggle', 'on', 'off'):
            return {'type': 'display_power', 'action': action}, None
        return None, 'dpms action not supported'
    if name == 'exit':
        return {'type': 'session', 'op': 'exit'}, None
    if name == 'no_op':
        return None, 'ignored'
    return None, f'no Luna action for dispatcher {name}'


LEGACY_SIMPLE = {'killactive': 'window.close', 'togglefloating': None, 'centerwindow': 'window.center',
                 'pin': 'window.pin', 'togglegroup': 'group.toggle', 'togglesplit': None,
                 'pseudo': 'window.pseudo', 'exit': 'exit'}


def legacy_dispatch(name, arg, mouse):
    """Turn a legacy dispatcher into (name, args) for map_disp. Return None if unknown."""
    if name == 'exec':
        return 'exec_cmd', [arg]
    if name in ('killactive', 'closewindow'):
        return 'window.close', []
    if name == 'togglefloating':
        return 'window.float', [{'action': 'toggle'}]
    if name == 'setfloating':
        return 'window.float', [{'action': 'enable'}]
    if name == 'settiled':
        return 'window.float', [{'action': 'disable'}]
    if name == 'fullscreen':
        return 'window.fullscreen', [{'mode': 'maximized' if arg.strip() == '1' else 'fullscreen', 'action': 'toggle'}]
    if name == 'movefocus':
        return 'focus', [{'direction': arg}]
    if name == 'focusmonitor':
        return 'focus', [{'monitor': arg}]
    if name == 'movewindow':
        if not arg:
            return ('window.drag', []) if mouse else None
        if arg.startswith('mon:'):
            return 'window.move', [{'monitor': arg[4:]}]
        return 'window.move', [{'direction': arg}]
    if name == 'resizewindow' and mouse and not arg:
        return 'window.resize', []
    if name == 'workspace':
        return 'focus', [{'workspace': arg}]
    if name in ('movetoworkspace', 'movetoworkspacesilent'):
        return 'window.move', [{'workspace': arg, 'follow': name == 'movetoworkspace'}]
    if name == 'resizeactive':
        parts = arg.split()
        if len(parts) == 2 and all(re.fullmatch(r'-?\d+', p) for p in parts):
            return 'window.resize', [{'x': int(parts[0]), 'y': int(parts[1]), 'relative': True}]
        return None
    if name == 'dpms':
        return 'dpms', [{'action': arg.strip() or 'toggle'}]
    if name == 'submap':
        return 'submap', [arg]
    if name == 'layoutmsg':
        return 'layout', [arg]
    if name == 'togglesplit':
        return 'layout', ['togglesplit']
    if name == 'alterzorder':
        return 'window.alter_zorder', [{'mode': arg.split(',')[0].strip()}]
    if name in LEGACY_SIMPLE and LEGACY_SIMPLE[name]:
        return LEGACY_SIMPLE[name], []
    if name == 'exit':
        return 'exit', []
    return None


