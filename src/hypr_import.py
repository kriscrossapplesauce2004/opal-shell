MOD_ORDER = ('super', 'ctrl', 'alt', 'shift', 'mod2', 'mod3', 'mod5')


def _combo_text(b):
    mods = sorted(b['mods'], key=MOD_ORDER.index)
    return '+'.join([m.upper() if m in ('super', 'ctrl', 'alt', 'shift') else m for m in mods] + [b['key']])


def _ident(b):
    return (tuple(sorted(b['mods'])), b['key'].lower(), b.get('mode'))


def _sig(action):
    """Return a comparable form of an action, with schema defaults filled in."""
    norm = dict(action)
    if norm.get('type') == 'space':
        norm['move_window'] = bool(norm.get('move_window', False))
        norm['follow'] = bool(norm.get('follow', True)) if norm['move_window'] else None
    return json.dumps(norm, sort_keys=True)


def diff_presets(user_binds, presets=PRESET_NAMES):
    """Compare the imported binds with each preset."""
    result = {}
    user = {}
    for b in user_binds:
        user[_ident(b)] = b
    for name in presets:
        preset = {}
        for b in PRESET_BUILDERS[name]():
            preset[_ident(b)] = b
        same, changed, only_user, only_preset = [], [], [], []
        for ident, b in user.items():
            if ident in preset:
                if _sig(b['action']) == _sig(preset[ident]['action']):
                    same.append(b)
                else:
                    changed.append({'user': b, 'preset': preset[ident]})
            else:
                only_user.append(b)
        for ident, b in preset.items():
            if ident not in user:
                only_preset.append(b)
        moved = []
        preset_by_sig = {}
        for b in only_preset:
            preset_by_sig.setdefault(_sig(b['action']), []).append(b)
        remaining_user = []
        for b in only_user:
            matches = preset_by_sig.get(_sig(b['action']))
            if matches:
                target = matches.pop(0)
                moved.append({'user': b, 'preset': target})
            else:
                remaining_user.append(b)
        gained = [b for lst in preset_by_sig.values() for b in lst]
        result[name] = {'same': same, 'changed': changed, 'moved': moved,
                        'lost': remaining_user, 'gained': gained}
    return result


def _action_text(action):
    return _sig(action)


def format_diff(diff):
    lines = []
    for name, d in diff.items():
        lines.append(f"== {name}: {len(d['same'])} same, {len(d['moved'])} moved key, "
                     f"{len(d['changed'])} changed, {len(d['lost'])} lost, {len(d['gained'])} gained")
        for m in d['moved']:
            lines.append(f"  moved   {_combo_text(m['user'])} -> {_combo_text(m['preset'])}  {_action_text(m['user']['action'])}")
        for c in d['changed']:
            lines.append(f"  changed {_combo_text(c['user'])}: yours {_action_text(c['user']['action'])}; preset {_action_text(c['preset']['action'])}")
        for b in d['lost']:
            lines.append(f"  lost    {_combo_text(b)}  {_action_text(b['action'])}  ({b.get('source', '')})")
        for b in d['gained']:
            lines.append(f"  gained  {_combo_text(b)}  {b.get('description', _action_text(b['action']))}")
    return '\n'.join(lines)


# ---------- CLI ----------

def format_report(rep):
    lines = []
    lines.append('Files loaded:')
    lines += [f'  {f}' for f in rep['files']['loaded']]
    if rep['files']['missing']:
        lines.append('Missing files:')
        lines += [f'  {f}' for f in rep['files']['missing']]
    lines.append('Counts: ' + ', '.join(f'{k}={v}' for k, v in rep['counts'].items()))
    lines.append(f"Redacted values: {rep['redacted']}")
    lines.append(f"Unmapped ({len(rep['unmapped'])}):")
    for u in rep['unmapped']:
        lines.append(f"  [{u['section']}] {u['item']}: {u['reason']} ({u['source']})")
    lines.append(f"Ignored ({len(rep['ignored'])}):")
    for u in rep['ignored']:
        lines.append(f"  {u['item']}: {u['reason']} ({u['source']})")
    if rep['errors']:
        lines.append(f"Errors ({len(rep['errors'])}):")
        for e in rep['errors']:
            lines.append(f"  {e['source']}: {e['message']}")
    if rep['notes']:
        lines.append('Notes:')
        lines += [f'  {n}' for n in rep['notes']]
    return '\n'.join(lines)


def _check_out(path):
    target = Path(path).expanduser().resolve()
    try:
        target.relative_to(HYPR_HOME.resolve())
    except ValueError:
        return target
    raise SystemExit(f'refusing to write under {HYPR_HOME}')


def main(argv=None):
    ap = argparse.ArgumentParser(description='Import a Hyprland config into the Luna WM schema (read only).')
    ap.add_argument('--config', default=str(DEFAULT_CONFIG), help='hyprland.lua or legacy hyprland.conf')
    ap.add_argument('--out', help='write the Luna config JSON here')
    ap.add_argument('--report', action='store_true', help='print the report')
    ap.add_argument('--preset', choices=PRESET_NAMES, help='emit a shortcut preset instead of importing')
    ap.add_argument('--diff-presets', action='store_true', help='compare your binds with each preset')
    ap.add_argument('--json', action='store_true', help='with --diff-presets, print JSON')
    ap.add_argument('--with-opal-overlay', action='store_true', help='also read the Opal overlay as if Opal is running')
    args = ap.parse_args(argv)

    if args.preset and not args.diff_presets:
        text = json.dumps(preset_config(args.preset), indent=2, ensure_ascii=False) + '\n'
        if args.out:
            _check_out(args.out).write_text(text, encoding='utf-8')
        else:
            sys.stdout.write(text)
        return 0

    try:
        cfg, rep = import_config(args.config, assume_opal=args.with_opal_overlay)
    except FileNotFoundError as err:
        print(f'config not found: {err}', file=sys.stderr)
        return 2

    if args.diff_presets:
        diff = diff_presets(cfg['keybinds'])
        if args.json:
            print(json.dumps(diff, indent=2, ensure_ascii=False))
        else:
            print(format_diff(diff))
            print(f"\n(Imported keybinds: {len(cfg['keybinds'])}; unmapped binds are not in the diff.)")
        return 0

    text = json.dumps(cfg, indent=2, ensure_ascii=False) + '\n'
    if args.out:
        _check_out(args.out).write_text(text, encoding='utf-8')
    if args.report:
        print(format_report(rep))
    if not args.out and not args.report:
        sys.stdout.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
