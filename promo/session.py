"""A recordable Opal session: the staging shell in a nested Hyprland inside a virtual (headless) KWin.

Nothing reaches the live desktop. The stack gets its own runtime folder (so no sockets or
runtime files collide with the live shell, and there is no PipeWire to change), its own
D-Bus session and its own Opal state folder. wf-recorder records the nested Hyprland output.
"""
import json, os, pathlib, shutil, signal, subprocess, sys, time
import fixture_home

STAGING = pathlib.Path(__file__).resolve().parent.parent
SRC = STAGING / 'src'
HOME = pathlib.Path.home()
LIVE_PREFS = HOME / '.local/state/opal/preferences.json'
STATE_ROOT = HOME / '.local/state/opal/promo-sessions'
CLIPS = HOME / '.local/state/opal/artifacts/promo/clips'
TOOLS = STAGING / 'tools'
KEYSYMS = {' ': 'space', '.': 'period', ',': 'comma', '/': 'slash', '-': 'minus', '=': 'equal', "'": 'apostrophe', ';': 'semicolon', '\n': 'Return', '~': 'asciitilde'}
SHIFTED = {'!': '1', '?': 'slash', ':': 'semicolon', '"': 'apostrophe', '(': '9', ')': '0', '*': '8', '+': 'equal', '_': 'minus', '|': 'backslash', '@': '2', '~': 'grave'}
CLOCKSHIFT = HOME / '.local/state/opal/promo-tools/clockshift.so'
LOOK_KEYS = ('palette', 'light', 'dynamicColors', 'dynamicPalette', 'colorScheme', 'glass', 'iconStyle', 'wallpaperPath',
             'wallpaperFit', 'wallpaper', 'wallpaperDim', 'favorites', 'weatherCity', 'phoneButtons', 'phoneRows', 'barStyle',
             'look', 'lookEdges', 'lookShadows', 'taskbarClockDate', 'pinned', 'pinsConfigured', 'phoneHome', 'gamePins')


class Session:
    def __init__(self, name, width, height, scale=1, prefs=None, fresh=True, clock='2026-10-24 09:41:00', battery=None, controller=False, media=True):
        self.name, self.width, self.height, self.scale = name, width, height, scale
        self.clock, self.battery, self.controller, self.media = clock, battery, controller, media
        self.state = STATE_ROOT / name
        self.runtime = pathlib.Path(f'/tmp/opr-{name}')
        if fresh and self.state.exists():
            shutil.rmtree(self.state)
        self.state.mkdir(parents=True, exist_ok=True)
        if self.runtime.exists():
            subprocess.run(['fusermount3', '-u', str(self.runtime / 'doc')], capture_output=True)
            shutil.rmtree(self.runtime, ignore_errors=True)
        self.runtime.mkdir(mode=0o700)
        self.extra_prefs = prefs or {}
        self.env = None
        self.recorder = None
        self.clip = None
        self.proc = None

    def write_prefs(self):
        try:
            live = json.loads(LIVE_PREFS.read_text())
        except (OSError, ValueError):
            live = {}
        prefs = {k: live[k] for k in LOOK_KEYS if k in live}
        # No theme files, no Link device, no Omarchy following and no autostart from the recorded shell.
        prefs.update(mode='desktop', phoneDisplay='WAYLAND-1', linkEnabled=False, themeExport=[], onboarded=True,
                     omarchyFollow=False, dnd=False, resumeSuggestions=False,
                     weatherCity='Lisbon', desktopIcons=False, desktopWidgets=True)
        prefs.update(self.extra_prefs)
        (self.state / 'preferences.json').write_text(json.dumps(prefs, indent=1))

    def write_configs(self):
        icon_theme = os.environ.get('QS_ICON_THEME') or subprocess.run(
            ['gsettings', 'get', 'org.gnome.desktop.interface', 'icon-theme'], capture_output=True, text=True).stdout.strip().strip("'")
        self.icon_theme = icon_theme
        (self.state / 'hyprland.lua').write_text(f'''-- Generated by promo/session.py.
hl.monitor({{ output = "WAYLAND-1", mode = "{self.width}x{self.height}", position = "0x0", scale = {self.scale} }})
hl.monitor({{ output = "", mode = "preferred", position = "auto", scale = 1 }})
hl.config({{ misc = {{ disable_hyprland_logo = true, disable_splash_rendering = true, disable_watchdog_warning = true }}, ecosystem = {{ no_update_news = true, no_donation_nag = true }}, cursor = {{ no_warps = true, inactive_timeout = 1 }} }})
dofile("{SRC}/hyprland.lua")
hl.on("hyprland.start", function()
    hl.exec_cmd("env > '{self.state}/env'")
    hl.exec_cmd("env OPAL_STATE_DIR='{self.state}' OPAL_NESTED=1 QS_ICON_THEME='{icon_theme}' LD_PRELOAD='{CLOCKSHIFT}' quickshell -n -p '{SRC}/shell.qml' > '{self.state}/shell.log' 2>&1")
end)
''')

    def start(self, settle=9):
        self.write_prefs()
        self.write_configs()
        env = {k: v for k, v in os.environ.items() if k not in ('WAYLAND_DISPLAY', 'DISPLAY', 'HYPRLAND_INSTANCE_SIGNATURE', 'SWAYSOCK', 'DBUS_SESSION_BUS_ADDRESS')}
        home, shims = fixture_home.build()
        mirror = home / '.local/state/opal'
        if mirror.is_symlink() or mirror.exists():
            mirror.unlink()
        mirror.parent.mkdir(parents=True, exist_ok=True)
        mirror.symlink_to(self.state)
        if self.clock:
            env.update(PROMO_CLOCK=subprocess.run(['date', '-d', self.clock, '+%s'], capture_output=True, text=True).stdout.strip(), PROMO_CLOCK_BASE=str(int(time.time())))
        if self.battery is not None:
            env['PROMO_BATTERY'] = str(self.battery)
        env.update(XDG_RUNTIME_DIR=str(self.runtime), HOME=str(home), PATH=f'{shims}:{env["PATH"]}', XDG_CONFIG_HOME=str(home / '.config'), XDG_DATA_HOME=str(home / '.local/share'),
                   XDG_STATE_HOME=str(home / '.local/state'), XDG_CACHE_HOME=str(home / '.cache'), QS_ICON_THEME=self.icon_theme, OPAL_STATE_DIR=str(self.state), OPAL_NESTED='1', OPAL_SHELL_PATH=str(SRC / 'shell.qml'))
        script = f'''
kwin_wayland --virtual --socket opal-parent --width {self.width + 80} --height {self.height + 80} --no-lockscreen > '{self.state}/kwin.log' 2>&1 &
for i in $(seq 100); do [[ -S $XDG_RUNTIME_DIR/opal-parent ]] && break; sleep .1; done
WAYLAND_DISPLAY=opal-parent exec Hyprland -c '{self.state}/hyprland.lua' > '{self.state}/hyprland.log' 2>&1
'''
        command = ['dbus-run-session', '--', 'bash', '-c', script]
        if not self.controller:
            # Hide /dev/input from the whole stack, so a connected gamepad does not bring up controller hints.
            command = ['unshare', '--user', '--map-root-user', '--mount', '--propagation', 'private', 'sh', '-c',
                       'mount -t tmpfs none /dev/input && exec unshare --user --map-user=1000 --map-group=1000 "$@"', 'promo', *command]
        self.proc = subprocess.Popen(['setsid', *command], env=env,
                                     stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        envfile = self.state / 'env'
        for _ in range(200):
            if envfile.exists() and 'HYPRLAND_INSTANCE_SIGNATURE' in envfile.read_text():
                break
            time.sleep(.1)
        else:
            raise RuntimeError('nested Hyprland did not start; see ' + str(self.state / 'hyprland.log'))
        time.sleep(.3)
        self.env = dict(line.split('=', 1) for line in envfile.read_text().splitlines() if '=' in line)
        # Guard: the stack must never share the live runtime folder.
        if self.env.get('XDG_RUNTIME_DIR') != str(self.runtime):
            self.stop()
            raise RuntimeError('nested session is not using its private runtime folder')
        if self.media:
            self.spawn(['python3', str(pathlib.Path(__file__).parent / 'tools/fake_mpris.py'), str(pathlib.Path(__file__).parent / 'tools/playlist.json')])
        self.wait_shell()
        time.sleep(settle)
        return self

    def wait_shell(self, timeout=40):
        end = time.time() + timeout
        while time.time() < end:
            if self.ipc('inspect', check=False):
                return
            time.sleep(.5)
        raise RuntimeError('shell did not answer; see ' + str(self.state / 'shell.log'))

    def run(self, args, check=True, capture=True, **kw):
        result = subprocess.run(args, env=self.env, capture_output=capture, text=True, timeout=kw.pop('timeout', 20), **kw)
        if check and result.returncode:
            raise RuntimeError(f'{args}: {result.stderr}')
        return result.stdout.strip() if capture else ''

    def spawn(self, args, **kw):
        return subprocess.Popen(args, env=self.env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, start_new_session=True, **kw)

    def ipc(self, fn, *args, check=True):
        try:
            return self.run(['quickshell', 'ipc', '-p', str(SRC / 'shell.qml'), 'call', 'opal', fn, *map(str, args)], check=check)
        except (RuntimeError, subprocess.TimeoutExpired):
            if check:
                raise
            return ''

    def pref(self, key, value):
        return self.ipc('setPreference', key, json.dumps(value))

    def hypr(self, *args):
        return self.run(['hyprctl', *args])

    def hypr_json(self, what):
        return json.loads(self.run(['hyprctl', '-j', what]))

    def actions(self):
        # Opal's own window actions (hypr_actions.py), pointed at the nested compositor.
        sys.path.insert(0, str(SRC))
        from hypr_actions import HyprActions
        return HyprActions(runner=lambda args: self.run(args, check=False))

    def window(self, cls):
        return next((c for c in self.hypr_json('clients') if c['class'] == cls), None)

    def lua(self, code):
        return self.run(['hyprctl', 'eval', code])

    def notify(self, app, summary, body='', icon='', urgency='normal'):
        return self.run(['notify-send', '-a', app, '-u', urgency] + (['-i', icon] if icon else []) + [summary, body])

    # Input through the nested compositor's virtual pointer and keyboard (tools/vpointer, tools/vkey). Coordinates are logical pixels.
    @property
    def logical(self):
        return round(self.width / self.scale), round(self.height / self.scale)

    def pointer(self, lines):
        return self.run([str(TOOLS / 'vpointer/vpointer')], input='\n'.join(lines) + '\n', timeout=60)

    def keys(self, lines):
        return self.run([str(TOOLS / 'vkey/vkey')], input='\n'.join(lines) + '\n', timeout=60)

    def move(self, x, y):
        w, h = self.logical
        self.cursor = (x, y)
        return self.pointer([f'move {x:.1f} {y:.1f} {w} {h}'])

    def glide(self, x, y, seconds=.6, click=False):
        # Eased (ease-in-out cubic) pointer travel at 60 Hz, then an optional click.
        w, h = self.logical
        x0, y0 = getattr(self, 'cursor', (w / 2, h / 2))
        steps = max(2, int(seconds * 60))
        lines = []
        for i in range(1, steps + 1):
            t = i / steps
            e = 4 * t ** 3 if t < .5 else 1 - (-2 * t + 2) ** 3 / 2
            lines += [f'move {x0 + (x - x0) * e:.1f} {y0 + (y - y0) * e:.1f} {w} {h}', 'sleep 16']
        if click:
            lines += ['sleep 60', 'down', 'sleep 90', 'up']
        self.cursor = (x, y)
        return self.pointer(lines)

    def click(self, x=None, y=None, seconds=.5):
        if x is None:
            return self.pointer(['down', 'sleep 90', 'up'])
        return self.glide(x, y, seconds, click=True)

    def drag(self, x0, y0, x1, y1, seconds=.6):
        w, h = self.logical
        self.glide(x0, y0, .3)
        steps = max(2, int(seconds * 60))
        lines = ['down', 'sleep 120']
        for i in range(1, steps + 1):
            t = i / steps
            e = 4 * t ** 3 if t < .5 else 1 - (-2 * t + 2) ** 3 / 2
            lines += [f'move {x0 + (x1 - x0) * e:.1f} {y0 + (y1 - y0) * e:.1f} {w} {h}', 'sleep 16']
        lines += ['sleep 80', 'up']
        self.cursor = (x1, y1)
        return self.pointer(lines)

    def combo(self, *names, hold=.05):
        return self.keys([f'down {n}' for n in names] + [f'sleep {int(hold * 1000)}'] + [f'up {n}' for n in reversed(names)])

    def tap(self, *names, gap=.08):
        out = []
        for n in names:
            out += [f'tap {n}', f'sleep {int(gap * 1000)}']
        return self.keys(out)

    def type(self, text, cps=14):
        lines = []
        for ch in text:
            name = KEYSYMS.get(ch, ch)
            if ch.isupper() or ch in SHIFTED:
                lines += ['down Shift_L', f'tap {SHIFTED.get(ch, ch.lower()) if ch in SHIFTED else ch.lower()}', 'up Shift_L']
            else:
                lines.append(f'tap {name}')
            lines.append(f'sleep {int(1000 / cps)}')
        return self.keys(lines)

    def shot(self, name):
        out = CLIPS.parent / 'shots' / f'{name}.png'
        out.parent.mkdir(parents=True, exist_ok=True)
        self.run(['grim', '-o', 'WAYLAND-1', str(out)])
        return out

    def record(self, clip):
        CLIPS.mkdir(parents=True, exist_ok=True)
        self.clip = CLIPS / f'{clip}.mkv'
        if self.clip.exists():
            self.clip.unlink()
        big = self.width * self.height > 2560 * 1600
        codec = ['-c', 'h264_vaapi', '-d', '/dev/dri/renderD128', '-p', 'qp=14'] if big else ['-c', 'libx264', '-p', 'preset=superfast', '-p', 'crf=12', '-x', 'yuv444p']
        self.recorder = subprocess.Popen(['wf-recorder', '-o', 'WAYLAND-1', '-D', '-r', '60', *codec, '-f', str(self.clip)],
                                         env=self.env, stdout=subprocess.DEVNULL, stderr=open(self.state / f'rec-{clip}.log', 'w'))
        time.sleep(1.0)
        return self.clip

    def stop_recording(self):
        if self.recorder:
            self.recorder.send_signal(signal.SIGINT)
            try:
                self.recorder.wait(20)
            except subprocess.TimeoutExpired:
                self.recorder.kill()
            self.recorder = None
        return self.clip

    def stop(self):
        self.stop_recording()
        # Every process of the stack carries the private runtime folder in its environment.
        marker = f'XDG_RUNTIME_DIR={self.runtime}'.encode()
        for sig in (signal.SIGTERM, signal.SIGKILL):
            for pid in os.listdir('/proc'):
                if not pid.isdigit() or int(pid) == os.getpid():
                    continue
                try:
                    if marker in pathlib.Path(f'/proc/{pid}/environ').read_bytes().split(b'\0'):
                        os.kill(int(pid), sig)
                except (OSError, PermissionError):
                    pass
            time.sleep(1.5)
        subprocess.run(['fusermount3', '-u', str(self.runtime / 'doc')], capture_output=True)
        shutil.rmtree(self.runtime, ignore_errors=True)
        if self.proc:
            try:
                self.proc.wait(5)
            except subprocess.TimeoutExpired:
                pass

    def __enter__(self):
        return self.start()

    def __exit__(self, *exc):
        self.stop()


class Attached(Session):
    """A handle on a session that serve() keeps running."""
    def __init__(self, name):
        self.name = name
        self.state = STATE_ROOT / name
        self.runtime = pathlib.Path(f'/tmp/opr-{name}')
        info = json.loads((self.state / 'serving').read_text())
        self.width, self.height, self.scale = info['width'], info['height'], info['scale']
        self.env = dict(line.split('=', 1) for line in (self.state / 'env').read_text().splitlines() if '=' in line)
        self.recorder, self.clip, self.proc = None, None, None
        cur = self.state / 'cursor'
        if cur.exists():
            self.cursor = tuple(json.loads(cur.read_text()))

    def save_cursor(self):
        if hasattr(self, 'cursor'):
            (self.state / 'cursor').write_text(json.dumps(list(self.cursor)))


def sleep(seconds):
    time.sleep(seconds)


def serve(name, width, height, scale, **kw):
    """Keep a session running for interactive exploration with ctl.py; SIGTERM stops it."""
    s = Session(name, width, height, scale, **kw)
    s.start()
    (s.state / 'serving').write_text(json.dumps({'width': width, 'height': height, 'scale': scale}))
    stop = []
    signal.signal(signal.SIGTERM, lambda *a: stop.append(1))
    signal.signal(signal.SIGINT, lambda *a: stop.append(1))
    try:
        while not stop:
            time.sleep(.5)
    finally:
        (s.state / 'serving').unlink(missing_ok=True)
        s.stop()


